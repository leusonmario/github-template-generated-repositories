#!/usr/bin/env python3
"""RQ2: weighted repository-level persistence dispersion (violin + ECDF).

Input: all_repository_pairs.csv generated by select_rq2_repository_cases_v2.py.
       This contains the COMPLETE RQ2 analyzed repository-pair sample,
       NOT only the cases selected for manual inspection.

Example:
  python -u plot_rq2_persistence_violin.py \
    --input rq2_repository_cases_v2/all_repository_pairs.csv \
    --output-dir rq2_distribution_figures

Outputs:
  rq2_persistence_violin.pdf / .png
  rq2_persistence_ecdf.pdf / .png
  rq2_persistence_dispersion_summary.csv

Interpretation:
  * One observation per source-template/generated-repository pair with at
    least one source-template finding of the relevant type.
  * Each observation = 100 * matched template findings / template findings.
  * Uses inverse-probability sampling weights from the RQ2 analysis.
  * Violin is the smoothed density among PARTIALLY persistent repositories
    (strictly between 0% and 100%); its width reflects their weighted share.
  * Endpoint circles show the weighted shares at EXACTLY 0% and 100%.
    This avoids smoothing large point masses at the boundaries into a violin.
  * Median and IQR summarize the FULL distribution, endpoints included.
  * ECDF gives the complete distribution without kernel smoothing.

Requirements: numpy, scipy, matplotlib.
"""

from __future__ import annotations

import argparse
import csv
import math
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.stats import gaussian_kde

LANGS = ["C#", "Java", "Python", "TypeScript", "JavaScript"]
KINDS = [("issues", "Quality issues"), ("hotspots", "Security Hotspots")]


def arguments():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--input", type=Path, required=True,
                   help="all_repository_pairs.csv (complete analyzed RQ2 sample)")
    p.add_argument("--output-dir", type=Path, default=Path("rq2_distribution_figures"))
    p.add_argument("--allow-unweighted", action="store_true",
                   help="Use weight=1 for missing weights; do not use for population claims")
    p.add_argument("--width", type=float, default=12.4)
    p.add_argument("--bw-adjust", type=float, default=0.85,
                   help="KDE bandwidth multiplier for the interior violin (default 0.85)")
    return p.parse_args()


def count(s, context):
    try:
        x = float(s)
    except (ValueError, TypeError):
        raise ValueError(f"{context}: expected integer, got {s!r}") from None
    if not math.isfinite(x) or x < 0 or x != int(x):
        raise ValueError(f"{context}: expected nonnegative integer, got {s!r}")
    return int(x)


def sampling_weight(s, lang, allow_unweighted):
    if s is None or not str(s).strip():
        if lang in ("Python", "TypeScript", "JavaScript") and not allow_unweighted:
            raise ValueError(f"Missing sampling_weight for {lang}; provide sample metadata when running "
                             "the repository-case selector, or set --allow-unweighted for an explicitly unweighted plot")
        return 1.0
    try:
        w = float(s)
    except (TypeError, ValueError):
        raise ValueError(f"Invalid sampling_weight {s!r}") from None
    if not math.isfinite(w) or w <= 0:
        raise ValueError(f"Invalid sampling_weight {s!r}")
    return w


def load(path, allow_unweighted):
    needed = {"language", "pair_id", "template_repository", "sampling_weight"}
    for kind, _ in KINDS:
        needed.update({f"{kind}_template", f"{kind}_persistent"})
    observations = {k: {l: [] for l in LANGS} for k, _ in KINDS}
    seen = set()
    overall = {l: 0 for l in LANGS}
    with path.open("r", encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        missing = needed - set(reader.fieldnames or [])
        if missing:
            raise ValueError(f"Input {path} lacks columns {sorted(missing)}")
        for line_number, row in enumerate(reader, 2):
            lang = row["language"].strip()
            if lang not in LANGS:
                raise ValueError(f"Unexpected language {lang!r} at line {line_number}")
            key = (lang, row["pair_id"].strip())
            if not key[1] or key in seen:
                raise ValueError(f"Missing or repeated pair_id at line {line_number}: {key!r}")
            seen.add(key)
            overall[lang] += 1
            w = sampling_weight(row.get("sampling_weight"), lang, allow_unweighted)
            template = row["template_repository"].strip()
            for kind, _ in KINDS:
                t = count(row[f"{kind}_template"], f"line {line_number} {kind} template")
                p = count(row[f"{kind}_persistent"], f"line {line_number} {kind} persistent")
                if p > t:
                    raise ValueError(f"Matched > template at line {line_number}, {kind}")
                if t == 0:
                    continue  # persistence is undefined, NOT zero
                observations[kind][lang].append((100.0 * p / t, w, template))
    if not seen:
        raise ValueError("Empty input file")
    return observations, overall


def weighted_quantile(values, weights, q):
    """Generalized weighted empirical quantile (left inverse of weighted ECDF)."""
    idx = np.argsort(values, kind="stable")
    v, w = values[idx], weights[idx]
    cutoff = q * float(w.sum())
    j = int(np.searchsorted(np.cumsum(w), cutoff, side="left"))
    return float(v[min(j, len(v)-1)])


def collect_summary(observations, overall):
    series, summary = {}, []
    for kind, title in KINDS:
        for lang in LANGS:
            rows = observations[kind][lang]
            v = np.array([r[0] for r in rows], dtype=float)
            w = np.array([r[1] for r in rows], dtype=float)
            total = float(w.sum())
            zero = float(w[v == 0].sum() / total * 100) if total else None
            full = float(w[v == 100].sum() / total * 100) if total else None
            partial = float(w[(v > 0) & (v < 100)].sum() / total * 100) if total else None
            stats = {
                "finding_type": kind, "language": lang,
                "total_analyzed_pairs_in_language": overall[lang],
                "eligible_pairs": len(v),
                "eligible_templates": len(set(r[2] for r in rows)),
                "sum_sampling_weights": total,
                "exact_zero_pct_of_repositories": zero,
                "partial_pct_of_repositories": partial,
                "exact_100_pct_of_repositories": full,
                "mean_repository_persistence_pct": float(np.dot(v,w)/total) if total else None,
                "p10_pct": weighted_quantile(v,w,.1) if total else None,
                "p25_pct": weighted_quantile(v,w,.25) if total else None,
                "median_pct": weighted_quantile(v,w,.5) if total else None,
                "p75_pct": weighted_quantile(v,w,.75) if total else None,
                "p90_pct": weighted_quantile(v,w,.9) if total else None,
            }
            summary.append(stats)
            series[(kind,lang)] = (v,w,stats)
    return series, summary


def interior_density(v,w,grid,bw_adjust):
    mask=(v > 0) & (v < 100)
    inside=v[mask]
    iw=w[mask]
    if len(inside)<2 or np.ptp(inside)<1e-9:
        return None
    try:
        estimator=gaussian_kde(inside, weights=iw,
                               bw_method=lambda kde: kde.scotts_factor()*bw_adjust)
        # Reflect evaluated points to keep estimated density within [0,100].
        # Do not mix point masses at 0 and 100 into a continuous density.
        density=estimator(grid) + estimator(-grid) + estimator(200-grid)
    except (np.linalg.LinAlgError, ValueError):
        return None
    if not np.all(np.isfinite(density)) or np.max(density)<=0:
        return None
    return density / np.max(density)


def save_figure(fig, out, name):
    for ext in ("pdf", "png"):
        fig.savefig(out / f"{name}.{ext}", dpi=280, bbox_inches="tight")
    plt.close(fig)


def plot_violin(series,out,width,bw_adjust):
    plt.rcParams.update({"font.family":"DejaVu Sans", "font.size":9,
                         "pdf.fonttype":42,"ps.fonttype":42,"axes.linewidth":.7})
    fig,axes=plt.subplots(1,2,figsize=(width,4.5),sharey=True)
    palette=plt.rcParams["axes.prop_cycle"].by_key()["color"]
    grid=np.linspace(0,100,241)
    for ax,(kind,title) in zip(axes,KINDS):
        ticklabels=[]
        for idx,lang in enumerate(LANGS,1):
            v,w,stat=series[(kind,lang)]
            ticklabels.append(f"{lang}\n(n={len(v):,})")
            if not len(v):
                ax.text(idx,50,"N/A",va="center",ha="center",fontsize=8)
                continue
            color=palette[idx-1]
            part=stat["partial_pct_of_repositories"]/100
            density=interior_density(v,w,grid,bw_adjust)
            if density is not None:
                half_width=.36*math.sqrt(part)
                # Light endpoint taper: the smoothed interior distribution
                # does not include the exact 0% and 100% masses.
                taper=np.minimum(1.0,grid/2.5)*np.minimum(1.0,(100-grid)/2.5)
                density=density*taper
                ax.fill_betweenx(grid,idx-density*half_width,idx+density*half_width,
                                 color=color,alpha=.43,linewidth=.8,edgecolor=color,zorder=2)
            else:
                interior=v[(v>0)&(v<100)]
                if interior.size:
                    for y in np.unique(interior):
                        ax.plot([idx-.11,idx+.11],[y,y],color=color,lw=2.4,zorder=3)
            # Median and IQR of the entire repository-level distribution,
            # including the exact-zero and exact-100 point masses.
            q1,q2,q3=(stat["p25_pct"],stat["median_pct"],stat["p75_pct"])
            ax.plot([idx,idx],[q1,q3],color="black",lw=4.0,solid_capstyle="round",zorder=6)
            ax.plot([idx-.075,idx+.075],[q1,q1],color="black",lw=1.1,zorder=6)
            ax.plot([idx-.075,idx+.075],[q3,q3],color="black",lw=1.1,zorder=6)
            ax.scatter([idx],[q2],s=34,facecolors="white",edgecolors="black",linewidths=1.0,zorder=7)
            # Endpoint proportions, shown explicitly rather than smoothed by KDE.
            for y,share in ((0,stat["exact_zero_pct_of_repositories"]),
                            (100,stat["exact_100_pct_of_repositories"])):
                if share and share>.00001:
                    size=14+145*share/100
                    ax.scatter([idx+.27],[y],s=size,facecolors=color,edgecolors="black",
                               linewidths=.5,alpha=.86,zorder=5,clip_on=False)
                    ax.text(idx+.40,y,f"{share:.0f}%",va="center",ha="left",
                            fontsize=7.1,color="0.25",zorder=7,clip_on=False)
        ax.set_title(title,pad=8,fontsize=11,fontweight="semibold")
        ax.set_xticks(range(1,6),ticklabels, fontsize=8)
        ax.set_xlim(.45,5.78)
        ax.set_ylim(-8,108)
        ax.set_yticks([0,25,50,75,100])
        ax.set_axisbelow(True)
        ax.yaxis.grid(True,color="0.86",lw=.5)
        ax.tick_params(length=0)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        ax.spines["bottom"].set_visible(False)
    axes[0].set_ylabel("Repository-level persistence (%)")
    fig.text(.5,.037,
        "Violin = partial persistence; circles = share at 0% and 100%. ",
        ha="center",va="center",fontsize=8.0,color="0.35")
    fig.text(.5,.011,"Thick line = weighted IQR; white dot = weighted median. "
                     "Repositories without template findings are excluded.",
             ha="center",va="center",fontsize=8.0,color="0.35")
    fig.subplots_adjust(wspace=.16,bottom=.20,left=.07,right=.995,top=.90)
    save_figure(fig,out,"rq2_persistence_violin")


def plot_ecdf(series,out,width):
    fig,axes=plt.subplots(1,2,figsize=(width,4.25),sharex=True,sharey=True)
    palette=plt.rcParams["axes.prop_cycle"].by_key()["color"]
    for ax,(kind,title) in zip(axes,KINDS):
        for i,lang in enumerate(LANGS):
            v,w,stats=series[(kind,lang)]
            if not len(v):continue
            order=np.argsort(v,kind="stable")
            sv,sw=v[order],w[order]
            # Collate repeated rates: makes steps for exact 0% and 100% explicit.
            unique,inverse=np.unique(sv,return_inverse=True)
            weights_by_value=np.bincount(inverse,weights=sw,minlength=len(unique))
            cumulative=100*np.cumsum(weights_by_value)/weights_by_value.sum()
            xx=np.r_[0.0, unique]
            yy=np.r_[0.0, cumulative]
            ax.step(xx,yy,where="post",lw=1.8,color=palette[i],label=f"{lang} (n={len(v):,})")
        ax.set_title(title,fontsize=11,fontweight="semibold")
        ax.set_xlim(0,100)
        ax.set_ylim(0,101)
        ax.set_xticks([0,25,50,75,100]);ax.set_yticks([0,25,50,75,100])
        ax.set_xlabel("Repository-level persistence (%)")
        ax.grid(True,alpha=.2)
        ax.legend(loc="upper left",fontsize=8,frameon=False)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
    axes[0].set_ylabel("Cumulative share of repositories (%)")
    fig.suptitle("Sampling-weighted empirical cumulative distribution",fontsize=11,y=.98)
    fig.subplots_adjust(wspace=.14,bottom=.14,left=.08,right=.98,top=.87)
    save_figure(fig,out,"rq2_persistence_ecdf")


def main():
    args=arguments()
    if args.bw_adjust<=0:raise ValueError("--bw-adjust must be positive")
    obs,overall=load(args.input,args.allow_unweighted)
    series,summary=collect_summary(obs,overall)
    args.output_dir.mkdir(parents=True,exist_ok=True)
    plot_violin(series,args.output_dir,args.width,args.bw_adjust)
    plot_ecdf(series,args.output_dir,args.width)
    dst=args.output_dir/"rq2_persistence_dispersion_summary.csv"
    with dst.open("w",encoding="utf-8",newline="") as file:
        writer=csv.DictWriter(file,fieldnames=list(summary[0]))
        writer.writeheader()
        writer.writerows(summary)
    print(f"Read {sum(overall.values()):,} repository pairs: "+", ".join(f"{k}={n:,}" for k,n in overall.items()))
    print("Eligibility: template findings > 0 for each finding type; rates at 0% and 100% retained exactly.")
    if args.allow_unweighted:print("WARNING: Missing weights treated as 1 (not suitable for weighted population inference).")
    print("\nLanguage        Type      Eligible  Median  IQR         0% share  100% share")
    for stat in summary:
        if not stat["eligible_pairs"]:continue
        print(f'{stat["language"]:<15} {stat["finding_type"]:<8} '
              f'{stat["eligible_pairs"]:>7}  {stat["median_pct"]:>6.1f}  '
              f'{stat["p25_pct"]:>5.1f}–{stat["p75_pct"]:<5.1f}  '
              f'{stat["exact_zero_pct_of_repositories"]:>7.1f}%  '
              f'{stat["exact_100_pct_of_repositories"]:>8.1f}%')
    print(f"\nSaved figures and summary to {args.output_dir.resolve()}")


if __name__=="__main__":
    main()
